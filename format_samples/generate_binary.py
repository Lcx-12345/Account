def build_sample_zip(path: Path) -> None:
    src_files = [
        ROOT / "README.md",
        ROOT / "sample.md",
        ROOT / "sample.html",
        ROOT / "sample.svg",
        ROOT / "sample.py",
        ROOT / "sample.json",
        OUT_DIR / "sample.pptx",
    ]

    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for f in src_files:
            if f.exists():
                zf.write(f, arcname=f.name)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    pptx_path = OUT_DIR / "sample.pptx"
    zip_path = OUT_DIR / "sample.zip"

    build_sample_pptx(pptx_path)
    build_sample_zip(zip_path)

    print(str(pptx_path))
    print(str(zip_path))


